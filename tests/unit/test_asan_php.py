"""Prove the actual sanitized PHP interpreter detects a bad native module."""
import os
import shutil
from pathlib import Path
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]


class AsanPhpVersionTests(unittest.TestCase):
    """Exercise real tag checkout and buildconf from a local fixture repository."""

    def run_version_probe(self, php_asan_version, *, missing_tag=False, retry=False,
                          missing_guard=False):
        with tempfile.TemporaryDirectory() as td:
            path = Path(td)
            repo = path / 'repo'
            repo.mkdir()
            subprocess.run(['git', 'init', '-q', str(repo)], check=True)

            def git(*args):
                subprocess.run(['git', '-C', str(repo), *args], check=True,
                               capture_output=True, text=True)

            git('config', 'user.email', 'fixture@example.com')
            git('config', 'user.name', 'Test')
            (repo / 'Zend').mkdir()
            (repo / 'Zend/zend_portability.h').write_text(
                'defined(__SANITIZE_ADDRESS__)' if not missing_guard else 'no sanitizer guard')
            # Git checkout has buildconf, and configure is generated by buildconf.
            (repo / 'buildconf').write_text("""#!/bin/sh
printf '%s\\n' "$@" > "$MOCK_BUILDCONF_LOG"
cat > configure <<'CONF'
#!/bin/sh
printf '%s\\n' "$@" > "$MOCK_CONFIGURE_LOG"
exit 89
CONF
chmod +x configure
""")
            (repo / 'buildconf').chmod(0o755)
            git('add', '.')
            git('commit', '-qm', 'php fixture 8.1.2')
            git('tag', '-a', 'php-8.1.2', '-m', 'PHP 8.1.2')
            (repo / 'dummy.txt').write_text('newer PHP fixture')
            git('add', '.')
            git('commit', '-qm', 'php fixture 8.4.11')
            if not missing_tag:
                git('tag', 'php-8.4.11')

            bin_dir = path / 'bin'
            bin_dir.mkdir()
            php = bin_dir / 'php'
            php.write_text("""#!/bin/sh
case "$*" in
  *PHP_MAJOR_VERSION*PHP_MINOR_VERSION*PHP_RELEASE_VERSION*)
    printf '8.1.2'
    ;;
  *)
    printf '8.1.2-1ubuntu2.28'
    ;;
esac
""")
            php.chmod(0o755)
            if retry:
                real_git = shutil.which('git')
                wrapper = bin_dir / 'git'
                wrapper.write_text("""#!/bin/sh
if [ "$1" = clone ] && [ ! -f "$MOCK_RETRY_MARKER" ]; then
    touch "$MOCK_RETRY_MARKER"
    exit 35
fi
exec """ + '"' + real_git + '"' + """ "$@"
""")
                wrapper.chmod(0o755)
            env = os.environ.copy()
            env.update({
                'PATH': str(bin_dir) + os.pathsep + env['PATH'],
                'PHP_ASAN_PREFIX': str(path / 'php-asan'),
                'PHP_ASAN_VERSION': php_asan_version,
                'PHP_ASAN_REPO': str(repo),
                'MOCK_BUILDCONF_LOG': str(path / 'buildconf-args.txt'),
                'MOCK_CONFIGURE_LOG': str(path / 'configure-args.txt'),
                'MOCK_RETRY_MARKER': str(path / 'retry-marker'),
            })
            result = subprocess.run(
                ['bash', str(ROOT / 'tools/asan/build-asan-php.sh')],
                env=env, capture_output=True, text=True, timeout=30)
            buildconf = path / 'buildconf-args.txt'
            configure = path / 'configure-args.txt'
            return (result,
                    buildconf.read_text() if buildconf.exists() else '',
                    configure.read_text() if configure.exists() else '',
                    (path / 'retry-marker').exists())

    def test_ubuntu_package_suffix_uses_exact_tag_and_bootstraps_configure(self):
        result, buildconf, configure, _ = self.run_version_probe('')
        self.assertEqual(result.returncode, 89, result.stderr)
        self.assertIn('Git tag php-8.1.2', result.stdout)
        self.assertIn('PHP source commit:', result.stdout)
        self.assertEqual(buildconf.strip(), '--force')
        self.assertIn('--disable-all', configure)
        self.assertIn('--enable-cli', configure)
        self.assertIn('--enable-address-sanitizer', configure)
        self.assertIn('--enable-debug', configure)
        self.assertNotIn('ubuntu', result.stdout)

    def test_explicit_upstream_version_uses_matching_git_tag(self):
        result, buildconf, configure, _ = self.run_version_probe('8.4.11')
        self.assertEqual(result.returncode, 89, result.stderr)
        self.assertIn('Git tag php-8.4.11', result.stdout)
        self.assertEqual(buildconf.strip(), '--force')
        self.assertIn('--enable-cli', configure)

    def test_transient_clone_failure_retries(self):
        result, buildconf, _, retried = self.run_version_probe('', retry=True)
        self.assertEqual(result.returncode, 89, result.stderr)
        self.assertTrue(retried)
        self.assertIn('retrying', result.stderr)
        self.assertEqual(buildconf.strip(), '--force')

    def test_nonexistent_git_tag_fails_closed(self):
        result, buildconf, _, _ = self.run_version_probe('8.4.11', missing_tag=True)
        self.assertEqual(result.returncode, 3)
        self.assertIn('unable to fetch PHP release tag php-8.4.11', result.stderr)
        self.assertFalse(buildconf)

    def test_missing_sanitizer_guard_fails_before_buildconf(self):
        result, buildconf, _, _ = self.run_version_probe('', missing_guard=True)
        self.assertEqual(result.returncode, 2)
        self.assertIn('sanitizer-aware Zend dlopen', result.stderr)
        self.assertFalse(buildconf)

    def test_invalid_explicit_version_fails_before_checkout(self):
        result, buildconf, _, _ = self.run_version_probe('8.1.2-1ubuntu2.28')
        self.assertEqual(result.returncode, 2)
        self.assertIn('invalid PHP_ASAN_VERSION', result.stderr)
        self.assertFalse(buildconf)


class AsanPhpTests(unittest.TestCase):
    def test_php_heap_overflow_is_detected(self):
        if os.environ.get('WALLETCORE_SANITIZE') != 'address':
            self.skipTest('diagnostic Docker target only')

        php_config = os.environ.get('PHP_CONFIG', '/opt/php-asan/bin/php-config')
        with tempfile.TemporaryDirectory() as td:
            path = Path(td)
            (path / 'probe.c').write_text(r'''
#include <stdlib.h>
#include "php.h"
PHP_FUNCTION(asan_probe) {
    volatile char *buffer = (volatile char *)malloc(8);
    volatile int index = 9;
    buffer[index] = 42;
    free((void *)buffer);
    RETURN_TRUE;
}
static const zend_function_entry probe_functions[] = {
    PHP_FE(asan_probe, NULL)
    PHP_FE_END
};
zend_module_entry asan_probe_module_entry = {
    STANDARD_MODULE_HEADER,
    "asan_probe", probe_functions, NULL, NULL, NULL, NULL, NULL,
    "0.1", STANDARD_MODULE_PROPERTIES
};
ZEND_GET_MODULE(asan_probe)
''')
            includes = subprocess.check_output(
                [php_config, '--includes'], text=True).strip().split()
            cc = os.environ.get('CLANG', 'clang')
            # Mirror build.sh: PHP's Zend/POSIX headers require the same
            # feature-test macros as the real walletcore.c translation unit.
            # On failure, include the actual compiler diagnostic in unittest
            # output; CalledProcessError alone hides the important stderr.
            command = [cc, '-std=c11', '-shared', '-fPIC', '-g', '-O1',
                       '-D_GNU_SOURCE', '-fsanitize=address',
                       '-fno-omit-frame-pointer',
                       '-DCOMPILE_DL_ASAN_PROBE=1', *includes,
                       str(path / 'probe.c'), '-o', str(path / 'asan_probe.so')]
            compiled = subprocess.run(command, capture_output=True, text=True)
            self.assertEqual(0, compiled.returncode,
                             'Failed to compile ASan probe against sanitized '
                             'PHP headers.\ncommand: ' + ' '.join(command) +
                             '\nstdout:\n' + compiled.stdout +
                             '\nstderr:\n' + compiled.stderr)
            env = os.environ.copy()
            env['ASAN_DETECT_LEAKS'] = '0'
            result = subprocess.run(
                ['bash', str(ROOT / 'tools/asan/run-asan-php.sh'), '-n',
                 '-d', 'display_errors=stderr',
                 '-d', 'display_startup_errors=1',
                 '-d', 'log_errors=1',
                 '-d', 'extension=' + str(path / 'asan_probe.so'),
                 '-r', 'if (!extension_loaded("asan_probe")) {'
                       'fwrite(STDERR, "asan_probe module not loaded\\n");'
                       'exit(42); } asan_probe();'],
                env=env, capture_output=True, text=True, timeout=30)
            # PHP can print fatal error output to stdout, and an old ASan
            # runtime may SIGSEGV before the module starts. Neither situation
            # proves that heap overflow instrumentation is working.
            details = (f'ASan negative probe exited {result.returncode}\n'
                       f'stdout:\n{result.stdout}\n'
                       f'stderr:\n{result.stderr}')
            self.assertNotEqual(result.returncode, 0, details)
            self.assertIn('AddressSanitizer: heap-buffer-overflow',
                          result.stdout + result.stderr, details)


if __name__ == '__main__':
    unittest.main()
